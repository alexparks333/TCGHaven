// Regenerates lib/scan/pokemonJaNames.ts — every Pokémon's Japanese name (katakana) → its English
// name, for reading Japanese cards (lib/scan/scanMatch.ts). From PokéAPI's open data
// (github.com/PokeAPI/pokeapi, data/v2/csv/pokemon_species_names.csv). Re-run when a new
// generation comes out: node scripts/gen-pokemon-ja-names.mjs
import fs from 'node:fs'
const url = 'https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species_names.csv'
const csv = await (await fetch(url, { headers: { 'User-Agent': 'TCGHaven-dev/1.0' } })).text()
const byId = {}
for (const line of csv.split('\n').slice(1)) {
  // pokemon_species_id,local_language_id,name,genus — names never contain commas
  const [id, lang, name] = line.split(',')
  if (!id || !name) continue
  ;(byId[id] ??= {})[lang] = name.trim()
}
const out = {}
for (const names of Object.values(byId)) {
  const ja = names['1'] ?? names['11'], en = names['9']   // 1 = ja-Hrkt (katakana), 9 = English
  if (ja && en) out[ja] = en
}
fs.writeFileSync(new URL('../lib/scan/pokemonJaNames.ts', import.meta.url),
  '// Generated by scripts/gen-pokemon-ja-names.mjs from PokéAPI\'s open data — don\'t edit by hand.\n' +
  '// Every Pokémon\'s Japanese name (as printed on Japanese cards) → its English name.\n' +
  `export const POKEMON_JA_NAMES: Record<string, string> = ${JSON.stringify(out)}\n`)
console.log(Object.keys(out).length, 'names')
